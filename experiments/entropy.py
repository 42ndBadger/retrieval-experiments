"""Shannon entropy, in bits per key, for each distribution family
generated by `src/data_gen.rs` - both the **analytical** (closed-form,
from the distribution's declared parameters) and, since the json-refactor
work, the **empirical** (measured from the actual generated data) value.
Earlier versions of this file computed only the analytical one
deliberately (see the old "Design decisions" note in CLAUDE.md, since
revised) - both are now produced side by side: analytical stays what
`rel_space_overhead` is computed against (so that metric doesn't move
based on which random keys got generated), empirical is exposed
separately for comparison/sanity-checking against it.
"""

from __future__ import annotations

import collections
import math
from pathlib import Path

from experiments.config import DatasetSpec


def uniform_entropy(bound: int) -> float:
    """rand's `Uniform::new(0, bound)` is half-open, so there are `bound`
    equally likely distinct values."""
    return math.log2(bound)


def bernoulli_entropy(p: float) -> float:
    """Binary entropy function H(p)."""
    if p <= 0.0 or p >= 1.0:
        return 0.0
    return -p * math.log2(p) - (1 - p) * math.log2(1 - p)


def truncated_geometric_entropy(p: float, bound: int) -> float:
    """`Geometric::new(p)` sampled then wrapped via `x % bound` (see
    data_gen.rs). The wrapped distribution is, for r in 0..bound:

        P(Y=r) = sum_{j=0..inf} (1-p)^(r + j*bound) * p
               = p * (1-p)^r / (1 - (1-p)^bound)

    (a geometric series over the "wrap" copies), which has a closed form
    computable directly from p and bound.
    """
    q = 1 - p
    denom = 1 - q**bound
    probs = [p * q**r / denom for r in range(bound)]
    return -sum(pr * math.log2(pr) for pr in probs if pr > 0.0)


def entropy_bits(spec: DatasetSpec) -> float:
    if spec.type == "uniform":
        return uniform_entropy(spec.params["bound"])
    if spec.type == "bernoulli":
        return bernoulli_entropy(spec.params["p"])
    if spec.type == "truncated_geometric":
        return truncated_geometric_entropy(spec.params["p"], spec.params["bound"])
    raise ValueError(f"unknown distribution type {spec.type!r}")


def empirical_entropy_bits(path: Path) -> float:
    """Shannon entropy (bits) of the empirical value distribution in a
    generated `.kv` file (`key value` per line, whitespace-separated -
    see datagen.py/naming.py::dataset_path). Values are compared as raw
    strings (not parsed as int/float), so this works the same way across
    all three distribution families without needing to know which one
    produced the file."""
    counts: collections.Counter[str] = collections.Counter()
    n = 0
    with path.open() as f:
        for line in f:
            parts = line.split()
            if len(parts) < 2:
                continue
            counts[parts[1]] += 1
            n += 1
    return -sum((c / n) * math.log2(c / n) for c in counts.values())
